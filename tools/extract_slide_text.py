"""Build assets/js/slide-text.js: the text of every page of every PDF in ch<N>/slides/ (every chapter folder),
for the site search (search.html finds keywords on individual slide pages).
Run after adding a deck:  python3 tools/extract_slide_text.py
Needs poppler's pdftotext. Math italic letters (U+1D400 block) are folded to plain ASCII via NFKC."""
import json, os, re, subprocess, sys, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAPTER_DIRS = sorted(d for d in os.listdir(ROOT) if re.fullmatch(r"ch\d+", d) and os.path.isdir(os.path.join(ROOT, d, "slides")))
out = {}
files = [(d, f) for d in CHAPTER_DIRS for f in sorted(os.listdir(os.path.join(ROOT, d, "slides"))) if f.endswith(".pdf")]
for i, (d, f) in enumerate(files, 1):
    path = os.path.join(ROOT, d, "slides", f)
    n = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", path], capture_output=True, text=True).stdout).group(1))
    pages = []
    for p in range(1, n + 1):
        t = subprocess.run(["pdftotext", "-f", str(p), "-l", str(p), "-layout", path, "-"], capture_output=True, text=True).stdout
        t = unicodedata.normalize("NFKC", t)
        t = re.sub(r"[ \t]+", " ", t)
        t = re.sub(r"\s*\n\s*", " / ", t.strip())
        pages.append(t)
    out[f"{d}/{f[:-4]}"] = pages
    print(f"[{i}/{len(files)}] {d}/{f}: {n} pages", file=sys.stderr)
js = "/* Generated by tools/extract_slide_text.py: page text of every PDF, keyed by <chapter dir>/<file name> (no .pdf). Used by search.html. */\nwindow.SLIDE_TEXT = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "assets", "js", "slide-text.js"), "w").write(js)
print(f"wrote assets/js/slide-text.js ({len(js)//1024} KB)", file=sys.stderr)
