"""Build assets/js/slide-text.js: the text of every page of every PDF in slides/decks/,
for the site search (search.html finds keywords on individual slide pages).
Run after adding a deck:  python3 tools/extract_slide_text.py
Needs poppler's pdftotext. Math italic letters (U+1D400 block) are folded to plain ASCII via NFKC."""
import json, os, re, subprocess, sys, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DECKS = os.path.join(ROOT, "slides", "decks")
out = {}
files = sorted(f for f in os.listdir(DECKS) if f.endswith(".pdf"))
for i, f in enumerate(files, 1):
    path = os.path.join(DECKS, f)
    n = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", path], capture_output=True, text=True).stdout).group(1))
    pages = []
    for p in range(1, n + 1):
        t = subprocess.run(["pdftotext", "-f", str(p), "-l", str(p), "-layout", path, "-"], capture_output=True, text=True).stdout
        t = unicodedata.normalize("NFKC", t)
        t = re.sub(r"[ \t]+", " ", t)
        t = re.sub(r"\s*\n\s*", " / ", t.strip())
        pages.append(t)
    out[f[:-4]] = pages
    print(f"[{i}/{len(files)}] {f}: {n} pages", file=sys.stderr)
js = "/* Generated by tools/extract_slide_text.py: page text of every deck PDF, keyed by file name (no .pdf). Used by search.html. */\nwindow.SLIDE_TEXT = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "assets", "js", "slide-text.js"), "w").write(js)
print(f"wrote assets/js/slide-text.js ({len(js)//1024} KB)", file=sys.stderr)
