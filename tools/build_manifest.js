/* Build assets/js/manifest.js — the list of homework sets and quizzes, per chapter, with their counts and tags.
 * Chapters come from assets/js/chapters.js; each chapter folder <dir>/ is scanned for hw/<set>/data.js and quizzes/<quiz>/data.js.
 * href / data are relative to the chapter folder (dir is on every entry).
 * The course home and chapter hubs draw their cards from it; the search page loads every listed data.js.
 * Run after adding or editing a set:  node tools/build_manifest.js */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const load = (file) => { global.window = {}; delete require.cache[require.resolve(file)]; require(file); return global.window; };
const secKey = (s) => s.split(/[.-]/).map(Number);
const bySec = (a, b) => { const x = secKey(a.sec), y = secKey(b.sec); return (x[0] - y[0]) || ((x[1] || 0) - (y[1] || 0)); };
const tagsOf = (items) => { const c = {}; items.forEach((it) => (it.tags || []).forEach((t) => (c[t] = (c[t] || 0) + 1))); return Object.keys(c).sort((a, b) => c[b] - c[a]).slice(0, 8); };

const CHAPTERS = load(path.join(ROOT, "assets", "js", "chapters.js")).CHAPTERS;
const sub = (dir, kind) => { const p = path.join(ROOT, dir, kind); return fs.existsSync(p) ? fs.readdirSync(p).filter((d) => fs.existsSync(path.join(p, d, "data.js"))) : []; };
const hw = [], quizzes = [];
CHAPTERS.forEach(({ ch, dir }, i) => {
  console.log(`[${i + 1}/${CHAPTERS.length}] chapter ${ch} (${dir}/)`);
  sub(dir, "hw").forEach((d) => {
    const H = load(path.join(ROOT, dir, "hw", d, "data.js")).HW;
    const slots = H.problems.reduce((t, p) => t + (p.parts ? p.parts.length : 1), 0);
    hw.push({ ch, dir, id: H.id, kind: "hw", sec: H.sec, title: H.title, href: `hw/${d}/index.html`, data: `hw/${d}/data.js`, deck: H.deck, quiz: H.quiz || null, problems: H.problems.length, slots, topics: tagsOf(H.problems) });
  });
  sub(dir, "quizzes").forEach((d) => {
    const Q = load(path.join(ROOT, dir, "quizzes", d, "data.js")).QUIZ;
    quizzes.push({ ch, dir, id: Q.id, kind: Q.kind || "quiz", sec: Q.sec, title: Q.short || Q.title, href: `quizzes/${d}/index.html`, data: `quizzes/${d}/data.js`, deck: Q.deck || null, hw: Q.hw || null, total: Q.questions.filter((q) => !q.pending).length, topics: tagsOf(Q.questions) });
  });
});
hw.sort((a, b) => (a.ch - b.ch) || bySec(a, b));
quizzes.sort((a, b) => (a.ch - b.ch) || (a.kind === b.kind ? 0 : a.kind === "quiz" ? -1 : 1) || bySec(a, b));

const js = `/* Generated by tools/build_manifest.js — do not edit by hand. Homework sets and quizzes per chapter, with counts and top tags; href/data are relative to the chapter folder (dir). */
window.MANIFEST = ${JSON.stringify({ hw, quizzes }, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, "assets", "js", "manifest.js"), js);
console.log(`manifest: ${hw.length} homework sets (${hw.reduce((t, h) => t + h.problems, 0)} problems), ${quizzes.length} quizzes (${quizzes.reduce((t, q) => t + q.total, 0)} questions)`);
