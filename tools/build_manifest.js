/* Build assets/js/manifest.js — the list of homework sets and quizzes with their counts and tags.
 * The hub (index.html) draws its cards from it and the search page loads every listed data.js.
 * Run after adding or editing a set:  node tools/build_manifest.js */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const load = (file) => { global.window = {}; delete require.cache[require.resolve(file)]; require(file); return global.window; };
const secKey = (s) => s.split(/[.-]/).map(Number);
const bySec = (a, b) => { const x = secKey(a.sec), y = secKey(b.sec); return (x[0] - y[0]) || ((x[1] || 0) - (y[1] || 0)); };
const tagsOf = (items) => { const c = {}; items.forEach((it) => (it.tags || []).forEach((t) => (c[t] = (c[t] || 0) + 1))); return Object.keys(c).sort((a, b) => c[b] - c[a]).slice(0, 8); };

const hw = fs.readdirSync(path.join(ROOT, "hw")).filter((d) => fs.existsSync(path.join(ROOT, "hw", d, "data.js"))).map((d) => {
  const H = load(path.join(ROOT, "hw", d, "data.js")).HW;
  const slots = H.problems.reduce((t, p) => t + (p.parts ? p.parts.length : 1), 0);
  return { id: H.id, kind: "hw", sec: H.sec, title: H.title, href: `hw/${d}/index.html`, data: `hw/${d}/data.js`, deck: H.deck, quiz: H.quiz || null, problems: H.problems.length, slots, topics: tagsOf(H.problems) };
}).sort(bySec);

const quizzes = fs.readdirSync(path.join(ROOT, "quizzes")).filter((d) => fs.existsSync(path.join(ROOT, "quizzes", d, "data.js"))).map((d) => {
  const Q = load(path.join(ROOT, "quizzes", d, "data.js")).QUIZ;
  return { id: Q.id, kind: Q.kind || "quiz", sec: Q.sec, title: Q.short || Q.title, href: `quizzes/${d}/index.html`, data: `quizzes/${d}/data.js`, deck: Q.deck || null, hw: Q.hw || null, total: Q.questions.filter((q) => !q.pending).length, topics: tagsOf(Q.questions) };
}).sort((a, b) => (a.kind === b.kind ? 0 : a.kind === "quiz" ? -1 : 1) || bySec(a, b));

const js = `/* Generated by tools/build_manifest.js — do not edit by hand. Homework sets and quizzes with counts and top tags. */
window.MANIFEST = ${JSON.stringify({ hw, quizzes }, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, "assets", "js", "manifest.js"), js);
console.log(`manifest: ${hw.length} homework sets (${hw.reduce((t, h) => t + h.problems, 0)} problems), ${quizzes.length} quizzes (${quizzes.reduce((t, q) => t + q.total, 0)} questions)`);
